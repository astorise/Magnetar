use super::*;

fn assert_selected(actual: &[(usize, f32)], expected: &[(usize, f32)]) {
    assert_eq!(actual.len(), expected.len());
    for &(index, weight) in expected {
        let found = actual
            .iter()
            .find(|(actual_index, _)| *actual_index == index)
            .unwrap();
        assert!(
            (found.1 - weight).abs() < 1e-6,
            "expert {index}: {} != {weight}",
            found.1
        );
    }
}

#[test]
fn olala_uses_biased_selection_and_unbiased_weights() {
    // Captured from the pinned Olala PyTorch forward path.
    let selected = sigmoid_moe_route(
        &[0.0, 2.0, -1.0, 0.4, -2.0],
        &[0.0, -0.9, 0.7, 0.15, 0.1],
        SigmoidRouting {
            top_k: 2,
            groups: None,
            normalization: SigmoidNormalization::MultipleExperts,
            scale: 2.45,
        },
    )
    .unwrap();
    assert_selected(&selected, &[(2, 0.759_433_45), (3, 1.690_566_7)]);
    let top_one = sigmoid_moe_route(
        &[0.3, -0.5, 2.0],
        &[0.0, 1.0, -1.0],
        SigmoidRouting {
            top_k: 1,
            groups: None,
            normalization: SigmoidNormalization::MultipleExperts,
            scale: 2.45,
        },
    )
    .unwrap();
    assert_selected(&top_one, &[(1, 0.924_974_7)]);
}

#[test]
fn olala_published_expert_count_matches_upstream_pytorch() {
    // Input construction and expected weights are from the pinned upstream
    // OlalaMoE fixture in components/olala/tests/fixtures.
    let logits: Vec<_> = (0..256)
        .map(|index| (((index * 37) % 257) as f32 - 128.0) / 37.0)
        .collect();
    let bias: Vec<_> = (0..256)
        .map(|index| (((index * 17) % 47) as f32 - 23.0) / 113.0)
        .collect();
    let selected = sigmoid_moe_route(
        &logits,
        &bias,
        SigmoidRouting {
            top_k: 6,
            groups: None,
            normalization: SigmoidNormalization::MultipleExperts,
            scale: 2.45,
        },
    )
    .unwrap();
    assert_selected(
        &selected,
        &[
            (69, 0.410_153_06),
            (152, 0.402_324_68),
            (243, 0.415_847_36),
            (55, 0.408_000_14),
            (138, 0.399_387_15),
            (229, 0.414_287_57),
        ],
    );
}

#[test]
fn glm_group_selection_and_top_one_normalization_match_transformers() {
    // Generated by tools/fixtures/sigmoid-routing/reference.py with the
    // Transformers 5.23.0 Glm4MoeLiteTopkRouter.
    let grouped = sigmoid_moe_route(
        &[2.0, -1.0, 0.2, -2.0, 1.0, 0.1, -1.0, 0.4],
        &[-0.9, 0.4, 0.0, 0.0, 0.0, 0.3, 0.1, 0.2],
        SigmoidRouting {
            top_k: 2,
            groups: Some(ExpertGroupSelection {
                count: 2,
                selected: 1,
            }),
            normalization: SigmoidNormalization::Always,
            scale: 2.45,
        },
    )
    .unwrap();
    assert_selected(&grouped, &[(5, 1.144_644_5), (7, 1.305_355_7)]);
    let top_one = sigmoid_moe_route(
        &[0.3, -0.5, 2.0, -0.2],
        &[0.0, 1.0, -1.0, 0.1],
        SigmoidRouting {
            top_k: 1,
            groups: Some(ExpertGroupSelection {
                count: 2,
                selected: 2,
            }),
            normalization: SigmoidNormalization::Always,
            scale: 2.45,
        },
    )
    .unwrap();
    assert_selected(&top_one, &[(1, 2.45)]);
    let saturated = sigmoid_moe_route(
        &[-100.0, -90.0, 100.0, 88.0, -80.0, -85.0, -70.0, -60.0],
        &[0.1, 0.2, 0.0, -0.1, 0.0, 0.1, 0.2, 0.3],
        SigmoidRouting {
            top_k: 1,
            groups: Some(ExpertGroupSelection {
                count: 2,
                selected: 1,
            }),
            normalization: SigmoidNormalization::Always,
            scale: 3.1,
        },
    )
    .unwrap();
    assert_selected(&saturated, &[(2, 3.1)]);
}

#[test]
fn zero_scores_and_selection_ties_are_handled_explicitly() {
    let options = SigmoidRouting {
        top_k: 1,
        groups: None,
        normalization: SigmoidNormalization::Always,
        scale: 2.0,
    };
    let zero = sigmoid_moe_route(&[-100.0, -100.0], &[1.0, 0.0], options).unwrap();
    assert_selected(&zero, &[(0, 0.0)]);
    assert!(sigmoid_moe_route(&[0.0, 0.0], &[0.0, 0.0], options).is_err());
    let groups = SigmoidRouting {
        groups: Some(ExpertGroupSelection {
            count: 2,
            selected: 1,
        }),
        ..options
    };
    assert!(sigmoid_moe_route(&[0.0; 4], &[0.0; 4], groups).is_err());
    assert!(sigmoid_moe_route(&[0.0; 3], &[0.0; 3], groups).is_err());
    assert!(sigmoid_moe_route(&[f32::NAN], &[0.0], options).is_err());
    assert!(sigmoid_moe_route(&[0.0], &[f32::INFINITY], options).is_err());
}

#[test]
fn incomplete_or_conflicting_routing_attributes_do_not_fall_back_to_softmax() {
    let mut attributes = BTreeMap::new();
    assert_eq!(
        sigmoid_routing_from_attributes(&attributes, 1).unwrap(),
        None
    );
    attributes.insert(
        "routing_normalization".into(),
        OperatorAttributeValue::String("always".into()),
    );
    assert!(sigmoid_routing_from_attributes(&attributes, 1).is_err());
    attributes.insert(
        "routing_scoring".into(),
        OperatorAttributeValue::String("sigmoid".into()),
    );
    assert!(sigmoid_routing_from_attributes(&attributes, 1).is_err());
    attributes.insert("routing_scale".into(), OperatorAttributeValue::Float(2.45));
    assert_eq!(
        sigmoid_routing_from_attributes(&attributes, 1)
            .unwrap()
            .unwrap()
            .normalization,
        SigmoidNormalization::Always
    );
    attributes.insert(
        "normalize_top_k".into(),
        OperatorAttributeValue::Boolean(false),
    );
    assert!(sigmoid_routing_from_attributes(&attributes, 1).is_err());
    attributes.insert(
        "normalize_top_k".into(),
        OperatorAttributeValue::Boolean(true),
    );
    attributes.insert(
        "routing_group_count".into(),
        OperatorAttributeValue::Integer(2),
    );
    assert!(sigmoid_routing_from_attributes(&attributes, 1).is_err());
    attributes.insert(
        "routing_group_selected".into(),
        OperatorAttributeValue::Integer(1),
    );
    assert_eq!(
        sigmoid_routing_from_attributes(&attributes, 1)
            .unwrap()
            .unwrap()
            .groups,
        Some(ExpertGroupSelection {
            count: 2,
            selected: 1
        })
    );
    attributes.insert(
        "routing_scale".into(),
        OperatorAttributeValue::Float(f64::MAX),
    );
    assert!(sigmoid_routing_from_attributes(&attributes, 1).is_err());
}
