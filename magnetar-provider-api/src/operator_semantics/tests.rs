#[test]
fn geodesic_residual_validates_shapes_values_and_layer_identity() {
    let x = HostTensor::new([2, 2], vec![1.0, 2.0, 3.0, 4.0]).unwrap();
    let g = HostTensor::new([2, 2], vec![2.0, -1.0, 4.0, -3.0]).unwrap();
    let scale = HostTensor::new([1], vec![1.0]).unwrap();
    let bias = HostTensor::new([], vec![0.0]).unwrap();
    let early = geodesic_residual(&x, &g, &scale, &bias, 0).unwrap();
    let late = geodesic_residual(&x, &g, &scale, &bias, 7).unwrap();
    assert_ne!(early.data, late.data);
    for row in 0..2 {
        let xr = HostTensor::new([1, 2], x.data[row * 2..row * 2 + 2].to_vec()).unwrap();
        let gr = HostTensor::new([1, 2], g.data[row * 2..row * 2 + 2].to_vec()).unwrap();
        assert_eq!(
            early.data[row * 2..row * 2 + 2],
            geodesic_residual(&xr, &gr, &scale, &bias, 0).unwrap().data
        );
    }
    let bad = HostTensor::new([2], vec![1.0, 2.0]).unwrap();
    let nan = HostTensor::new([1], vec![f32::NAN]).unwrap();
    assert!(geodesic_residual(&x, &g, &bad, &bias, 0).is_err());
    assert!(geodesic_residual(&x, &bad, &scale, &bias, 0).is_err());
    assert!(geodesic_residual(&x, &g, &nan, &bias, 0).is_err());
    assert!(geodesic_residual(&x, &g, &scale, &bias, u32::MAX).is_err());
}
