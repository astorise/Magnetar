"""Benchmark Strata's resident Qwen3.6 engine on exactly the llama.cpp prompt IDs."""
import json
import os
import queue
import subprocess
import threading
import time
from pathlib import Path

from common import sha256


def run(args, raw_dir):
    if args.device != "gpu" or not args.binary or not args.model_path:
        raise ValueError("Strata Qwen3.6 requires a GPU, engine binary and GGUF model")
    ids_path = os.environ.get("BENCH_PROMPT_IDS_PATH")
    if not ids_path or not Path(ids_path).is_file():
        raise ValueError("Strata requires the prompt IDs generated by the preceding llama.cpp run")
    ids = json.loads(Path(ids_path).read_text(encoding="utf-8"))
    if not isinstance(ids, list) or not ids or any(type(t) is not int or t < 0 for t in ids):
        raise ValueError("Invalid Strata prompt IDs")
    model = Path(args.model_path).resolve()
    if not model.is_file():
        raise ValueError("Strata GGUF model is missing")
    binary = Path(args.binary).resolve()
    raw_dir.mkdir(parents=True, exist_ok=False)
    cmd = [str(binary), "--model", str(model), "--serve", "--max-context", "512", "--mtp", "0"]
    env = os.environ.copy()
    dirs = [binary.parent]
    try:
        build = json.loads((binary.parent / "BUILD.json").read_text(encoding="utf-8-sig"))
        for name in build.get("lib_dirs", []):
            path = Path(name)
            if name and not path.is_absolute() and ".." not in path.parts and (binary.parent / path).is_dir():
                dirs.append(binary.parent / path)
    except (OSError, ValueError, TypeError):
        pass
    env["LD_LIBRARY_PATH"] = os.pathsep.join([*(str(d) for d in dirs), env.get("LD_LIBRARY_PATH", "")])
    messages = queue.Queue()
    with (raw_dir / "stderr.txt").open("w", encoding="utf-8") as err, \
            (raw_dir / "stdout.txt").open("w", encoding="utf-8") as out:
        process = subprocess.Popen(cmd, stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=err,
                                   text=True, encoding="utf-8", errors="replace", bufsize=1, env=env)

        def pump():
            for line in process.stdout:
                out.write(line)
                out.flush()
                messages.put(line.strip())
            messages.put(None)

        reader = threading.Thread(target=pump, daemon=True)
        reader.start()

        def next_line(timeout):
            try:
                line = messages.get(timeout=timeout)
            except queue.Empty as error:
                raise RuntimeError("Timed out waiting for the Strata engine") from error
            if line is None:
                raise RuntimeError(f"Strata engine exited before completing a request; inspect {raw_dir}")
            if line.startswith("ERR"):
                raise RuntimeError(f"Strata engine rejected request: {line}")
            return line

        try:
            deadline = time.monotonic() + 900
            info = []
            while True:
                line = next_line(max(0.01, deadline - time.monotonic()))
                if line.startswith("INFO "):
                    info.append(line)
                if line.startswith("READY"):
                    break
                if time.monotonic() >= deadline:
                    raise RuntimeError("Strata did not become ready within 15 minutes")
            samples = []
            prompt = ",".join(str(t) for t in ids)
            for index in range(args.runs + 1):
                started = time.perf_counter()
                process.stdin.write(f"GEN {args.tokens} temperature=0 penalty_repeat=1 {prompt}\n")
                process.stdin.flush()
                tokens = []
                first_token = None
                while True:
                    line = next_line(3600)
                    if line.startswith("T "):
                        if first_token is None:
                            first_token = time.perf_counter() - started
                        tokens.append(int(line.split()[1]))
                    elif line.startswith("DONE "):
                        elapsed = time.perf_counter() - started
                        parts = line.split()
                        if len(parts) < 9 or int(parts[1]) != len(tokens) or not tokens:
                            raise RuntimeError(f"Unexpected Strata DONE response: {line}")
                        if index:
                            samples.append({"prompt_tokens": len(ids), "generated_tokens": len(tokens),
                                            "generated_token_ids": tokens, "request_seconds": elapsed,
                                            "request_tokens_per_second": len(tokens) / elapsed,
                                            "time_to_first_token_ms": first_token * 1000,
                                            "cached_prompt_tokens": int(parts[8]), "finish_reason": parts[5]})
                        break
        finally:
            if process.stdin:
                process.stdin.close()
            try:
                process.wait(timeout=15)
            except subprocess.TimeoutExpired:
                process.terminate()
                try:
                    process.wait(timeout=15)
                except subprocess.TimeoutExpired:
                    process.kill()
                    process.wait()
            reader.join(timeout=15)
            if process.stdout:
                process.stdout.close()
    return {"protocol": "resident local Strata engine; one warmup, native token protocol, MTP disabled; "
                        "prompt IDs from llama.cpp; hybrid CPU/GPU placement",
            "device_evidence": {"cuda_visible_devices": env.get("CUDA_VISIBLE_DEVICES"), "engine_info": info},
            "model": {"path": str(model), "weights_sha256": sha256(model)},
            "dtype": "GGUF UD-Q4_K_XL mixed weights", "command": cmd, "samples": samples}
